def skill_category(key: str) -> tuple[str, str]:
    """(category, category_source) for a canonical skill key."""
    if key in KAGGLE_OVERRIDES:
        return KAGGLE_OVERRIDES[key], "kaggle (corrected)"
    if key in KAGGLE_SKILL_TYPES:
        return KAGGLE_TYPE_LABELS[KAGGLE_SKILL_TYPES[key]], "kaggle"
    if key in CURATED:
        return CURATED[key], "curated"
    return "Uncategorized", "none"


def is_technical(category: str) -> bool:
    """Soft skills and spoken languages are the only non-technical groups.
    Uncategorized skills are counted as technical (they come from tech postings)."""
    return category not in NON_TECHNICAL
